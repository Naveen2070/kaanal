// Outlines "kaanal" in Inter SemiBold into src/look/brand/wordmark.ts, so the loader's wordmark is a path:
// it cannot shift when the fonts swap, and the reflection images draw exactly the same shape. Run
// by hand when the lockup changes; the output is committed and is the only thing the app imports.
//
// opentype.js reads TTF/OTF/WOFF but not WOFF2 or a variable instance, so the input is the static
// SemiBold WOFF from the same Fontsource release as src/fonts (OFL 1.1, see FONTS.md), fetched once
// into a scratch folder and not committed:
//
//   npm pack @fontsource/inter@5.3.0 && tar -xzf fontsource-inter-5.3.0.tgz
//   node scripts/wordmark.mjs <that folder>/package/files/inter-latin-600-normal.woff

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";

const TEXT = "kaanal";
const SIZE = 100; // units per em of the output: the loader scales it
const TRACKING = -0.02; // em, a touch tighter than the text face, as drawn in the brand sheet

export function outline(fontBytes) {
  const font = opentype.parse(fontBytes.buffer.slice(fontBytes.byteOffset));
  // one glyph per letter: "kaanal" has no ligature, and opentype.js's shaper trips on Inter's ccmp
  const glyphs = TEXT.split("").map((ch) => font.charToGlyph(ch));
  const scale = SIZE / font.unitsPerEm;
  const path = new opentype.Path();
  let x = 0;
  glyphs.forEach((g, i) => {
    path.extend(g.getPath(x, 0, SIZE));
    const next = glyphs[i + 1];
    const kern = next ? font.getKerningValue(g, next) : 0;
    x += (g.advanceWidth + kern) * scale + TRACKING * SIZE;
  });
  const box = path.getBoundingBox();
  // the left edge of the "k" at x = 0, the baseline at y = 0 (the path is above it: y < 0)
  for (const c of path.commands) {
    for (const k of ["x", "x1", "x2"]) if (k in c) c[k] -= box.x1;
  }
  return {
    d: path.toPathData(1),
    width: +(box.x2 - box.x1).toFixed(1),
    top: +(-box.y1).toFixed(1),
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const input = process.argv[2];
  if (!input) {
    console.error("usage: node scripts/wordmark.mjs <inter-latin-600-normal.woff>");
    process.exit(2);
  }
  const w = outline(readFileSync(input));
  const out = resolve(fileURLToPath(import.meta.url), "../../src/look/brand/wordmark.ts");
  writeFileSync(
    out,
    `// Generated by scripts/wordmark.mjs from Inter SemiBold (OFL 1.1): do not edit by hand.\n` +
      `// "${TEXT}" at ${SIZE} units per em; the "k" starts at x = 0, the baseline is y = 0.\n\n` +
      `export const WORDMARK = {\n  d: ${JSON.stringify(w.d)},\n  width: ${w.width},\n  top: ${w.top},\n};\n`,
  );
  console.log(`wrote ${out} (width ${w.width}, top ${w.top}, ${w.d.length} chars)`);
}
