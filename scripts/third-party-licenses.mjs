#!/usr/bin/env node
// Writes THIRD_PARTY_LICENSES.md: the notices for everything that ships inside a kaanal release (the
// binary's Rust crates, Studio's JavaScript libraries, its fonts, the price data). The file is committed
// and goes into every release archive and npm package (RULES 150).
//
// Usage:
//   node scripts/third-party-licenses.mjs           regenerate (needs cargo-about, and ui/node_modules)
//   node scripts/third-party-licenses.mjs --check   fail if Cargo.lock or ui/pnpm-lock.yaml changed since
//                                                    the file was written (cheap: no tools needed)
//
// Install cargo-about once: cargo install cargo-about --locked --features cli
// Rust: cargo-about, with about.toml (the accepted licences) and about.hbs (the layout).
// JavaScript: `pnpm licenses list --prod`, plus each package's own LICENSE file.
// Fonts: licenses/fonts/*.txt, the OFL texts from the pinned @fontsource packages (ui/FONTS.md).

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "THIRD_PARTY_LICENSES.md");
const LOCKS = ["Cargo.lock", "ui/pnpm-lock.yaml"];

const sha = (rel) => createHash("sha256").update(readFileSync(join(root, rel))).digest("hex");
const stamp = () => LOCKS.map((f) => `${f}=${sha(f)}`).join(" ");

if (process.argv.includes("--check")) {
  const head = existsSync(OUT) ? readFileSync(OUT, "utf8").split("\n", 1)[0] : "";
  if (head !== `<!-- ${stamp()} -->`) {
    console.error("THIRD_PARTY_LICENSES.md is out of date: run node scripts/third-party-licenses.mjs");
    process.exit(1);
  }
  console.log("THIRD_PARTY_LICENSES.md matches the lock files");
  process.exit(0);
}

const run = (cmd, args, cwd) =>
  execFileSync(cmd, args, { cwd, encoding: "utf8", maxBuffer: 256 * 1024 * 1024, stdio: ["ignore", "pipe", "inherit"] });

// --- Rust crates (cargo-about)
// (cargo-about wants -o FILE: on Windows it refuses to write to a pipe)
const tmp = mkdtempSync(join(tmpdir(), "about-"));
run(
  "cargo",
  ["about", "generate", "--config", "about.toml", "--manifest-path", "crates/kaanal/Cargo.toml", "-o", join(tmp, "rust.md"), "about.hbs"],
  root,
);
const rust = readFileSync(join(tmp, "rust.md"), "utf8").trim();
rmSync(tmp, { recursive: true, force: true });

// --- Studio's JavaScript libraries: one entry per distinct licence text
const ui = join(root, "ui");
const listed = JSON.parse(run("pnpm", ["licenses", "list", "--prod", "--json"], ui));
const FILES = ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "LICENCE.md", "license", "license.md", "license.txt"];
const byText = new Map();
for (const [licence, pkgs] of Object.entries(listed)) {
  for (const p of pkgs) {
    const dir = p.paths[0];
    const file = FILES.find((f) => existsSync(join(dir, f)));
    if (!file) throw new Error(`no licence file in ${dir} (${p.name}); add it by hand`);
    const text = readFileSync(join(dir, file), "utf8").trim();
    if (!byText.has(text)) byText.set(text, { licence, pkgs: [] });
    byText.get(text).pkgs.push(`${p.name} ${p.versions.join(", ")}`);
  }
}
const js = [...byText.entries()]
  .sort(([, a], [, b]) => a.pkgs[0].localeCompare(b.pkgs[0]))
  .map(([text, { licence, pkgs }]) => `### ${licence}\n\nUsed by:\n${pkgs.sort().map((n) => `- ${n}`).join("\n")}\n\n\`\`\`text\n${text}\n\`\`\``)
  .join("\n\n");

// --- Fonts
const fontDir = join(root, "licenses", "fonts");
const fonts = readdirSync(fontDir)
  .sort()
  .map((f) => `### ${f.replace(/-OFL-1\.1\.txt$/, "")} (SIL Open Font License 1.1)\n\n\`\`\`text\n${readFileSync(join(fontDir, f), "utf8").trim()}\n\`\`\``)
  .join("\n\n");

const doc = `<!-- ${stamp()} -->
# Third-party licenses

Kaanal itself is licensed under the Apache License 2.0 (\`LICENSE\`). A release contains the third-party
software listed below, each under its own licence. This file is generated by
\`scripts/third-party-licenses.mjs\`: do not edit it by hand.

## Rust crates in the \`kaanal\` binary

${rust}

## JavaScript libraries in Studio

Studio's bundle (the graphical editor served at \`/__kaanal/studio\`) contains these production dependencies.

${js}

## Fonts in Studio

Self-hosted, unchanged or subset; see \`ui/FONTS.md\`. The copyright holders are named at the top of each text.

${fonts}

## Price and instance data

\`crates/kaanal-core/data/\` holds instance specifications and on-demand prices of AWS, Azure and Google Cloud.
They are read from each provider's public price and instance pages through the catalogue kept by
instances.vantage.sh (a mirror of those pages), and from AWS's own price files for DocumentDB and Neptune.
Provider names and instance type names belong to their owners and are used only to identify instance types.
The figures are estimates for what-if simulation, not quotes. Kaanal is not affiliated with or endorsed by
Amazon, Microsoft or Google.
`;
writeFileSync(OUT, doc.replace(/\r\n/g, "\n").replace(/[ \t]+\n/g, "\n"));
console.log(`wrote ${OUT}`);
