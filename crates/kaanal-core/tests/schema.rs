use kaanal_core::config_schema;
use serde_json::Value;
use std::path::{Path, PathBuf};

fn root() -> &'static Path {
    Path::new(env!("CARGO_MANIFEST_DIR"))
}

#[test]
fn committed_schema_matches_the_types() {
    let generated = config_schema();
    let path = root().join("kaanal.schema.json");
    if std::env::var_os("KAANAL_BLESS").is_some() {
        std::fs::write(
            &path,
            serde_json::to_string_pretty(&generated).unwrap() + "\n",
        )
        .unwrap();
    }
    let committed: Value = serde_json::from_str(&std::fs::read_to_string(&path).unwrap()).unwrap();
    assert_eq!(
        committed, generated,
        "the config schema changed: regenerate with KAANAL_BLESS=1 cargo test -p kaanal-core --test schema, then review the diff"
    );
}

/// Every shipped example and the server fixture.
fn shipped_configs() -> Vec<PathBuf> {
    let mut files: Vec<PathBuf> = std::fs::read_dir(root().join("../../examples"))
        .unwrap()
        .map(|e| e.unwrap().path().join("kaanal.yaml"))
        .filter(|p| p.is_file())
        .collect();
    files.sort();
    files.push(root().join("../kaanal-server/tests/fixtures/kaanal.yaml"));
    files
}

#[test]
fn shipped_configs_validate_against_the_schema() {
    let validator = jsonschema::validator_for(&config_schema()).unwrap();
    let files = shipped_configs();
    assert!(files.len() >= 2, "{files:?}");
    for f in files {
        let doc: Value = serde_yaml_ng::from_str(&std::fs::read_to_string(&f).unwrap()).unwrap();
        let errors: Vec<String> = validator
            .iter_errors(&doc)
            .map(|e| format!("{}: {e}", e.instance_path()))
            .collect();
        assert!(errors.is_empty(), "{}: {errors:?}", f.display());
    }
}

/// Every property schema in the document, as ("Owner.field", schema). The `type` tag of
/// node branches is generated by schemars and has no description.
fn properties(s: &Value) -> Vec<(String, Value)> {
    let mut objects: Vec<(String, &Value)> = vec![("Config".into(), s)];
    for (name, def) in s["$defs"].as_object().unwrap() {
        objects.push((name.clone(), def));
        for (i, b) in def["oneOf"].as_array().into_iter().flatten().enumerate() {
            objects.push((format!("{name}[{i}]"), b));
        }
    }
    objects
        .into_iter()
        .flat_map(|(owner, o)| {
            o["properties"]
                .as_object()
                .into_iter()
                .flatten()
                .filter(|(k, _)| k.as_str() != "type")
                .map(move |(k, v)| (format!("{owner}.{k}"), v.clone()))
        })
        .collect()
}

#[test]
fn every_schema_field_has_a_description() {
    let missing: Vec<String> = properties(&config_schema())
        .into_iter()
        .filter(|(_, v)| v["description"].as_str().is_none_or(str::is_empty))
        .map(|(k, _)| k)
        .collect();
    assert!(missing.is_empty(), "add a doc comment to: {missing:?}");
}

#[test]
fn inert_fields_say_they_have_no_effect_yet() {
    let s = config_schema();
    let branches = s["$defs"]["NodeConfig"]["oneOf"].as_array().unwrap();
    let field = |kind: &str, name: &str| {
        let b = branches
            .iter()
            .find(|b| b["properties"]["type"]["const"] == kind)
            .unwrap();
        b["properties"][name]["description"]
            .as_str()
            .unwrap_or_default()
            .to_string()
    };
    for (kind, name) in [
        ("database", "pool"),
        ("external-api", "error_rate"),
        ("external-api", "rate_limit"),
        ("external-api", "proxy"),
        ("external-api", "pool"),
        ("cache", "ttl"),
    ] {
        let d = field(kind, name);
        assert!(d.contains("no effect yet"), "{kind}.{name}: {d:?}");
    }
}

#[test]
fn schema_describes_endpoints_and_steps() {
    let s = config_schema();
    assert!(s["properties"].get("routes").is_none(), "routes: is gone");
    for key in ["endpoints", "determinism"] {
        assert!(s["properties"].get(key).is_some(), "{key}");
    }
    assert_eq!(s["$defs"]["Step"]["oneOf"].as_array().unwrap().len(), 4);
    let service = s["$defs"]["NodeConfig"]["oneOf"]
        .as_array()
        .unwrap()
        .iter()
        .find(|b| b["properties"]["type"]["const"] == "service")
        .unwrap();
    assert!(service["properties"].get("chains").is_some(), "{service}");
    let doc: Value = serde_yaml_ng::from_str(
        "version: 1\nnodes:\n  app: { type: service, chains: { r: [ db ] } }\nendpoints:\n  \"GET /x\":\n    chain: [ { cache: c }, { call: a, repeat: 2 }, { parallel: [ a, [ b, c ] ] } ]\n    error_map: { db: 503, \"5xx\": { status: 502, body: { e: 1 } } }\n",
    )
    .unwrap();
    let v = jsonschema::validator_for(&s).unwrap();
    let errors: Vec<String> = v.iter_errors(&doc).map(|e| e.to_string()).collect();
    assert!(errors.is_empty(), "{errors:?}");
    let file: Value =
        serde_yaml_ng::from_str("version: 1\nnodes: {}\nendpoints: kaanal.endpoints.yaml\n")
            .unwrap();
    assert!(v.is_valid(&file));
}

#[test]
fn schema_describes_auth_claims_and_scopes() {
    let s = config_schema();
    let auth = s["$defs"]["NodeConfig"]["oneOf"]
        .as_array()
        .unwrap()
        .iter()
        .find(|b| b["properties"]["type"]["const"] == "auth")
        .unwrap();
    assert_eq!(
        auth["properties"]["claims"]["additionalProperties"]["type"],
        serde_json::json!(["string", "number", "boolean"]),
        "{auth}"
    );
    let user = &s["$defs"]["UserConfig"]["properties"];
    assert!(
        user.get("scopes").is_some() && user.get("claims").is_some(),
        "{user}"
    );
    let doc: Value = serde_yaml_ng::from_str(
        "version: 1\nnodes:\n  login: { type: auth, claims: { aud: a, n: 1 }, users: [ { username: a, password: b, scopes: [read], claims: { ok: true } } ] }\n",
    )
    .unwrap();
    assert!(jsonschema::validator_for(&s).unwrap().is_valid(&doc));
}
